local _, ns = ...

local function LuaKey(name)
	if name:match("^[%a_][%w_]*$") then
		return name
	end
	return ("[%q]"):format(name)
end

local function AppendActionBars(lines)
	local values = {}
	for i, enabled in ipairs(ns.CurrentActionBarToggles()) do
		values[i] = tostring(enabled)
	end
	lines[#lines + 1] = "\t-- Bars 2 to 8, in Blizzard's settings order."
	lines[#lines + 1] = ("\tactionBars = { %s },"):format(table.concat(values, ", "))
end

-- Bindings keep Blizzard's order and category headers, which makes the
-- exported file read like the in-game keybinding menu.
local function AppendBindings(lines)
	lines[#lines + 1] = "\tbindings = {"
	local lastCategory
	for index = 1, GetNumBindings() do
		local command, category = GetBinding(index)
		local keys = ns.GetBindingKeys(index)
		if #keys > 0 then
			if category ~= lastCategory then
				lastCategory = category
				lines[#lines + 1] = ("\t\t-- %s"):format(ns.BindingCategoryName(category, "?"))
			end
			for _, key in ipairs(keys) do
				lines[#lines + 1] = ("\t\t[%q] = %q,"):format(key, command)
			end
		end
	end
	lines[#lines + 1] = "\t},"
end

local function AppendCVars(lines)
	local entries = {}
	ns.ForEachCVar(function(name, value, defaultValue)
		if value ~= defaultValue and not ns.IsIgnoredCVar(name) then
			entries[#entries + 1] = ("\t\t%s = %q,"):format(LuaKey(name), value)
		end
	end)
	table.sort(entries)

	lines[#lines + 1] = "\tcvars = {"
	tAppendAll(lines, entries)
	lines[#lines + 1] = "\t},"
end

function ns.BuildProfileExport()
	local lines = {
		"local _, ns = ...",
		"",
		("-- Generated by /sui export on %s; edit freely."):format(date("%Y-%m-%d %H:%M")),
		"-- A section that is nil is not managed; an empty bindings table would unbind every key.",
		"ns.config.settings.profile = {",
	}
	AppendActionBars(lines)
	lines[#lines + 1] = ""
	AppendBindings(lines)
	lines[#lines + 1] = ""
	AppendCVars(lines)
	lines[#lines + 1] = "}"
	lines[#lines + 1] = ""
	return table.concat(lines, "\n")
end
