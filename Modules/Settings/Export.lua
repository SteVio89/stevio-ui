local addonName, ns = ...

local config = ns.config.settings

local function IsIgnoredCVar(name)
	for _, pattern in ipairs(config.ignoredCVars) do
		if name:find(pattern) then
			return true
		end
	end
	return false
end

local function LuaKey(name)
	if name:match("^[%a_][%w_]*$") then
		return name
	end
	return ("[%q]"):format(name)
end

local function AppendActionBars(lines)
	local values = {}
	for i = 1, select("#", GetActionBarToggles()) do
		values[i] = tostring(not not select(i, GetActionBarToggles()))
	end
	lines[#lines + 1] = "\t-- Bars 2 to 8, in Blizzard's settings order."
	lines[#lines + 1] = ("\tactionBars = { %s },"):format(table.concat(values, ", "))
end

-- Bindings keep Blizzard's order and category headers, which makes the
-- exported file read like the in-game keybinding menu.
local function AppendBindings(lines)
	lines[#lines + 1] = "\tbindings = {"
	local lastCategory
	for index = 1, GetNumBindings() do
		local command, category = GetBinding(index)
		local keys = ns.GetBindingKeys(index)
		if #keys > 0 then
			if category ~= lastCategory then
				lastCategory = category
				lines[#lines + 1] = ("\t\t-- %s"):format(category and _G[category] or category or "?")
			end
			for _, key in ipairs(keys) do
				lines[#lines + 1] = ("\t\t[%q] = %q,"):format(key, command)
			end
		end
	end
	lines[#lines + 1] = "\t},"
end

local function AppendCVars(lines)
	local entries = {}
	for _, info in ipairs(ConsoleGetAllCommands()) do
		local name = info.command
		if info.commandType == Enum.ConsoleCommandType.Cvar and not IsIgnoredCVar(name) then
			local value, defaultValue, _, _, isLocked, isSecure, isReadOnly = C_CVar.GetCVarInfo(name)
			if value and value ~= defaultValue and not isLocked and not isSecure and not isReadOnly then
				entries[#entries + 1] = ("\t\t%s = %q,"):format(LuaKey(name), value)
			end
		end
	end
	table.sort(entries)

	lines[#lines + 1] = "\tcvars = {"
	tAppendAll(lines, entries)
	lines[#lines + 1] = "\t},"
end

function ns.BuildProfileExport()
	local lines = {
		"local _, ns = ...",
		"",
		("-- Generated by /sui export on %s; edit freely."):format(date("%Y-%m-%d %H:%M")),
		"-- A section that is nil is not managed; an empty bindings table would unbind every key.",
		"ns.config.settings.profile = {",
	}
	AppendActionBars(lines)
	lines[#lines + 1] = ""
	AppendBindings(lines)
	lines[#lines + 1] = ""
	AppendCVars(lines)
	lines[#lines + 1] = "}"
	lines[#lines + 1] = ""
	return table.concat(lines, "\n")
end

local window

local function CreateWindow()
	local frame = CreateFrame("Frame", "StevioUI_ExportWindow", UIParent)
	local width, height = 760, 560
	frame:SetSize(width, height)
	frame:SetPoint("CENTER")
	frame:SetFrameStrata("DIALOG")
	ns.CreateBackground(frame):SetColorTexture(0.05, 0.05, 0.05, 0.95)
	ns.CreateBorder(frame)
	-- Lets Escape close the window like any Blizzard panel.
	tinsert(UISpecialFrames, frame:GetName())

	local title = ns.CreateFontString(frame, 12)
	title:SetPoint("TOPLEFT", 10, -10)
	title:SetText(("%s – Profile.lua (Cmd+A, Cmd+C)"):format(addonName))

	local close = CreateFrame("Button", nil, frame, "UIPanelCloseButton")
	close:SetPoint("TOPRIGHT", 2, 2)

	local scroll = CreateFrame("ScrollFrame", nil, frame, "UIPanelScrollFrameTemplate")
	scroll:SetPoint("TOPLEFT", 10, -32)
	scroll:SetPoint("BOTTOMRIGHT", -30, 10)

	local editBox = CreateFrame("EditBox", nil, scroll)
	editBox:SetMultiLine(true)
	editBox:SetAutoFocus(false)
	editBox:SetFontObject(ChatFontNormal)
	-- Scroll children need an explicit width; anchors don't size them.
	editBox:SetWidth(width - 40)
	editBox:SetScript("OnEscapePressed", function()
		frame:Hide()
	end)
	scroll:SetScrollChild(editBox)

	frame.editBox = editBox
	return frame
end

function ns.ShowExportWindow(text)
	window = window or CreateWindow()
	window.editBox:SetText(text)
	window:Show()
	window.editBox:SetFocus()
	window.editBox:HighlightText()
end
