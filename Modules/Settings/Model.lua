local _, ns = ...

-- The decisions behind the profile's overrides and its export, apart from the
-- client API (Client.lua) so they can be tested outside the game.

local Model = {}
ns.SettingsModel = Model

-- Overrides ------------------------------------------------------------------

-- CVar names are case-insensitive; the spelling in the first of `maps` (name ->
-- value) that knows the CVar wins, else `name` as it is.
function Model.KnownCVarName(name, maps)
	local lower = name:lower()
	for _, map in ipairs(maps) do
		for known in pairs(map) do
			if known:lower() == lower then
				return known
			end
		end
	end
	return name
end

-- The override for a CVar the player changed to `value`. Back at the
-- profile's value (or, for a CVar outside the profile, at the game default)
-- there is none.
function Model.CVarOverrideFor(value, defaultValue, profileValue)
	if value == (profileValue or defaultValue) then
		return nil
	end
	return value
end

-- The override for a key set to `command` in the options panel (nil unbinds
-- it); none for the profile's own command, `false` for unbinding a key the
-- profile binds.
function Model.BindingOverride(command, profileCommand)
	if command == profileCommand then
		return nil
	elseif command == nil then
		if profileCommand then
			return false
		end
		return nil
	end
	return command
end

-- The override for a CVar set to `value` in the options panel (nil removes
-- it), and whether the CVar goes back to the game default because it is no
-- longer managed (outside the profile).
function Model.CVarOverride(value, profileValue)
	local override = value
	if value == nil or value == profileValue then
		override = nil
	end
	return override, value == nil and profileValue == nil
end

-- Adds the profile's bindings whose command the client doesn't know this
-- session (an addon turned off) to `current`, so they count as unchanged
-- instead of removed. `commands` is the set of commands the client knows.
function Model.AddUnknownProfileBindings(current, commands, profileBindings)
	for key, command in pairs(profileBindings) do
		if current[key] == nil and not commands[command] then
			current[key] = command
		end
	end
	return current
end

-- Export ---------------------------------------------------------------------

-- Whether CVar `name` matches one of `patterns` (Lua patterns).
function Model.IsIgnoredCVar(name, patterns)
	for _, pattern in ipairs(patterns) do
		if name:find(pattern) then
			return true
		end
	end
	return false
end

function Model.LuaKey(name)
	if name:match("^[%a_][%w_]*$") then
		return name
	end
	return ("[%q]"):format(name)
end

local function AppendActionBars(lines, actionBars)
	local values = {}
	for i, enabled in ipairs(actionBars) do
		values[i] = tostring(enabled)
	end
	lines[#lines + 1] = "\t-- Bars 2 to 8, in Blizzard's settings order."
	lines[#lines + 1] = ("\tactionBars = { %s },"):format(table.concat(values, ", "))
end

-- Bindings keep Blizzard's order and category headers, which makes the
-- exported file read like the in-game keybinding menu.
local function AppendBindings(lines, bindings)
	lines[#lines + 1] = "\tbindings = {"
	local lastCategory
	for _, binding in ipairs(bindings) do
		if #binding.keys > 0 then
			if binding.category ~= lastCategory then
				lastCategory = binding.category
				lines[#lines + 1] = ("\t\t-- %s"):format(binding.categoryName)
			end
			for _, key in ipairs(binding.keys) do
				lines[#lines + 1] = ("\t\t[%q] = %q,"):format(key, binding.command)
			end
		end
	end
	lines[#lines + 1] = "\t},"
end

local function AppendCVars(lines, cvars)
	local entries = {}
	for _, cvar in ipairs(cvars) do
		entries[#entries + 1] = ("\t\t%s = %q,"):format(Model.LuaKey(cvar.name), cvar.value)
	end
	table.sort(entries)

	lines[#lines + 1] = "\tcvars = {"
	for _, entry in ipairs(entries) do
		lines[#lines + 1] = entry
	end
	lines[#lines + 1] = "\t},"
end

-- The text of a Profile.lua. `stamp` is the export's date and time,
-- `actionBars` the bar toggles, `bindings` Blizzard's binding list as
-- { command, category, categoryName, keys } and `cvars` a list of
-- { name, value }, in any order.
function Model.ProfileText(stamp, actionBars, bindings, cvars)
	local lines = {
		"local _, ns = ...",
		"",
		("-- Generated by /sui export on %s; edit freely."):format(stamp),
		"-- A section that is nil is not managed; an empty bindings table would unbind every key.",
		"ns.config.settings.profile = {",
	}
	AppendActionBars(lines, actionBars)
	lines[#lines + 1] = ""
	AppendBindings(lines, bindings)
	lines[#lines + 1] = ""
	AppendCVars(lines, cvars)
	lines[#lines + 1] = "}"
	lines[#lines + 1] = ""
	return table.concat(lines, "\n")
end
