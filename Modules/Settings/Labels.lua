-- "fadeInTime" -> "Fade in time"
local function Words(key)
	local spaced = key:gsub("(%l)(%u)", "%1 %2"):lower()
	return spaced:sub(1, 1):upper() .. spaced:sub(2)
end

-- Label and help text (nil when there is none) of config key `key`.
function ns.ConfigLabel(key)
	if type(key) ~= "string" then
		return tostring(key)
	end
	local entry = labels[key]
	if entry then
		if ns.isGerman then
			return entry[2], entry[4]
		end
		return entry[1], entry[3]
	end
	if key:match("^[%u%d_]+$") then
		return key
	end
	return Words(key)
end
